import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { recommendSpeciality } from '@/lib/vector/recommend';
 
type Row = { text: string; speciality_name: string };
 
async function main() {
  const rows: Row[] = JSON.parse(readFileSync(path.resolve(process.cwd(), '../vector/eval.json'), 'utf8'));
  let top1 = 0, top3 = 0;
  const per = new Map<string, { n: number; hit1: number; hit3: number }>();
  const misses: string[] = [];
 
  for (const r of rows) {
    const rec = await recommendSpeciality(r.text);
    const rank = rec.alternatives.findIndex((a) => a.specialityName === r.speciality_name);
    const ok1 = rec.specialityName === r.speciality_name;
    const ok3 = rank >= 0 && rank < 3;
    if (ok1) top1++;
    if (ok3) top3++;
    const s = per.get(r.speciality_name) ?? { n: 0, hit1: 0, hit3: 0 };
    s.n++; if (ok1) s.hit1++; if (ok3) s.hit3++;
    per.set(r.speciality_name, s);
    if (!ok1) misses.push(`- "${r.text}" -> expected **${r.speciality_name}**, got **${rec.specialityName}** (confidence ${(rec.confidence * 100).toFixed(0)}%)`);
  }
 
  const pct = (a: number, b: number) => `${((100 * a) / b).toFixed(1)}%`;
  const lines = [
    '# Retrieval evaluation',
    '',
    `Generated by \`npm run qdrant:eval\` on ${new Date().toISOString()}.`,
    `Held-out cases: ${rows.length} (\`vector/eval.json\`). Model: all-MiniLM-L6-v2, Cosine, top-K vote.`,
    '',
    `| Metric | Result | Target |`,
    `|---|---|---|`,
    `| Top-1 accuracy | ${pct(top1, rows.length)} (${top1}/${rows.length}) | >= 70% |`,
    `| Top-3 accuracy | ${pct(top3, rows.length)} (${top3}/${rows.length}) | >= 90% |`,
    '',
    '## Per speciality',
    '',
    '| Speciality | Cases | Top-1 | Top-3 |',
    '|---|---|---|---|',
    ...[...per.entries()].map(([k, v]) => `| ${k} | ${v.n} | ${v.hit1}/${v.n} | ${v.hit3}/${v.n} |`),
    '',
    '## Top-1 misses',
    '',
    ...(misses.length ? misses : ['None.']),
    '',
  ];
  const out = lines.join('\n');
  console.log(out);
  writeFileSync(path.resolve(process.cwd(), '../docs/testing/retrieval-eval.md'), out);
  process.exit(top1 / rows.length >= 0.7 && top3 / rows.length >= 0.9 ? 0 : 2);
}
 
main().catch((e) => { console.error(e); process.exit(1); });
